    /** Splits text into lines of at most maxChars (on spaces). */
    public static List<String> wrap(String text, int maxChars) {
        List<String> lines = new ArrayList<>();
        StringBuilder line = new StringBuilder();
        for (String word : text.trim().toUpperCase().split("\\s+")) {
            if (word.isEmpty()) continue;
            if (line.length() > 0 && line.length() + 1 + word.length() > maxChars) {
                lines.add(line.toString());
                line.setLength(0);
            }
            if (line.length() > 0) line.append(' ');
            line.append(word);
        }
        if (line.length() > 0) lines.add(line.toString());
        return lines;
    }

    /**
     * Lit pixels of the text, centred: each entry is {column, row} with (0,0) at the centre, columns to the right,
     * rows up. Characters are 6 columns apart, lines 9 rows apart.
     */
    public static List<float[]> pixels(List<String> lines) {
        List<float[]> out = new ArrayList<>();
        int maxLen = 0;
        for (String l : lines) maxLen = Math.max(maxLen, l.length());
        float totalH = lines.size() * 9 - 2;
        for (int li = 0; li < lines.size(); li++) {
            String line = lines.get(li);
            float width = line.length() * 6 - 1;
            for (int ci = 0; ci < line.length(); ci++) {
                String[] rows = GLYPHS.getOrDefault(line.charAt(ci), GLYPHS.get('?'));
                for (int r = 0; r < H; r++) {
                    for (int c = 0; c < W; c++) {
                        if (rows[r].charAt(c) != '#') continue;
                        float x = ci * 6 + c - width / 2 + 0.5F;
                        float y = totalH / 2 - (li * 9 + r) - 0.5F;
                        out.add(new float[]{x, y});
                    }
                }
            }
        }
        return out;
    }

    public static int maxLineLength(List<String> lines) {
        int m = 0;
        for (String l : lines) m = Math.max(m, l.length());
        return m;
    }
